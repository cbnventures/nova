/**
 * Landing Page - Escape HTML.
 *
 * Encodes project-owned text before it enters the starter homepage markup.
 * Generated projects can safely reuse the renderer with customized names.
 *
 * @param {Worker_LandingPage_EscapeHtml_Value} value - Value.
 *
 * @returns {Worker_LandingPage_EscapeHtml_Returns}
 *
 * @since 0.0.0
 */
function escapeHtml(value: Worker_LandingPage_EscapeHtml_Value): Worker_LandingPage_EscapeHtml_Returns {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll('\'', '&#39;');
}

