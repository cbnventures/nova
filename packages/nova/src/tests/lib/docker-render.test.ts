/**
 * Tests - Lib - Docker Render - Copy Directory.
 *
 * Copies every file below one fixture folder into a sandbox folder, creating
 * the parent folders as it goes.
 *
 * @param {Tests_Lib_DockerRender_CopyDirectory_Source} source - Source.
 * @param {Tests_Lib_DockerRender_CopyDirectory_Target} target - Target.
 *
 * @returns {Tests_Lib_DockerRender_CopyDirectory_Returns}
 *
 * @since 0.49.0
 */
async function copyDirectory(source: Tests_Lib_DockerRender_CopyDirectory_Source, target: Tests_Lib_DockerRender_CopyDirectory_Target): Tests_Lib_DockerRender_CopyDirectory_Returns {
  const entries: Tests_Lib_DockerRender_CopyDirectory_Entries = await readdir(source, {
    recursive: true,
    withFileTypes: true,
  });

  await Promise.all(entries.filter((entry) => entry.isFile() === true).map(async (entry) => {
    const targetPath: Tests_Lib_DockerRender_CopyDirectory_TargetPath = join(target, relative(source, join(entry.parentPath, entry.name)));

    await mkdir(dirname(targetPath), { recursive: true });

    await copyFile(join(entry.parentPath, entry.name), targetPath);

    return;
  }));

  return;
}

/**
 * Tests - Lib - Docker Render - Render Fixture.
 *
 * Copies one fixture project into the sandbox, runs the same sync the recipe
 * runs, and returns the rendered and current Dockerfile and compose.yml.
 *
 * @param {Tests_Lib_DockerRender_RenderFixture_FixtureName} fixtureName - Fixture name.
 * @param {Tests_Lib_DockerRender_RenderFixture_SandboxRoot} sandboxRoot - Sandbox root.
 *
 * @returns {Tests_Lib_DockerRender_RenderFixture_Returns}
 *
 * @since 0.49.0
 */
async function renderFixture(fixtureName: Tests_Lib_DockerRender_RenderFixture_FixtureName, sandboxRoot: Tests_Lib_DockerRender_RenderFixture_SandboxRoot): Tests_Lib_DockerRender_RenderFixture_Returns {
  const projectDirectory: Tests_Lib_DockerRender_RenderFixture_ProjectDirectory = await mkdtemp(join(sandboxRoot, `${fixtureName}-`));

  await copyDirectory(join(fixturesDirectory, fixtureName, 'project'), projectDirectory);

  await LibDockerPackaging.syncImage({
    projectDirectory,
    replaceFile: true,
    reportFiles: false,
  });

  const files: Tests_Lib_DockerRender_RenderFixture_Files = await Promise.all([
    readFile(join(projectDirectory, 'Dockerfile'), 'utf-8'),
    readFile(join(projectDirectory, 'compose.yml'), 'utf-8'),
    readFile(join(fixturesDirectory, fixtureName, 'current', 'Dockerfile'), 'utf-8'),
    readFile(join(fixturesDirectory, fixtureName, 'current', 'compose.yml'), 'utf-8'),
  ]);
  const currentDockerfileLines: Tests_Lib_DockerRender_RenderFixture_CurrentDockerfileLines = (files[2] ?? '').split('\n');

  // The generated-file headers are the allowed difference, so they are added to each current file first.
  return [
    files[0] ?? '',
    files[1] ?? '',
    [
      currentDockerfileLines[0] ?? '',
      '',
      ...((fixtureName === 'transmission-vpn') ? stagedDockerfileHeader : dockerfileHeader),
      ...currentDockerfileLines.slice(1),
    ].join('\n'),
    [
      ...composeHeader,
      '',
      files[3] ?? '',
    ].join('\n'),
  ];
}

/**
 * Tests - Lib - Docker Render - Apply Differences.
 *
 * Applies each documented difference to a repository's current file. Every
 * "before" block must occur exactly once, so a stale list fails loudly.
 *
 * @param {Tests_Lib_DockerRender_ApplyDifferences_Content}     content     - Content.
 * @param {Tests_Lib_DockerRender_ApplyDifferences_Differences} differences - Differences.
 *
 * @returns {Tests_Lib_DockerRender_ApplyDifferences_Returns}
 *
 * @since 0.49.0
 */
function applyDifferences(content: Tests_Lib_DockerRender_ApplyDifferences_Content, differences: Tests_Lib_DockerRender_ApplyDifferences_Differences): Tests_Lib_DockerRender_ApplyDifferences_Returns {
  let updated: Tests_Lib_DockerRender_ApplyDifferences_Updated = content;

  for (const difference of differences) {
    const before: Tests_Lib_DockerRender_ApplyDifferences_Before = difference['before'].join('\n');

    strictEqual(updated.split(before).length, 2, `Expected exactly one block for the difference: ${difference['reason']}`);

    updated = updated.split(before).join(difference['after'].join('\n'));
  }

  return updated;
}

