import { strictEqual } from 'node:assert/strict';
import {
  mkdir,
  mkdtemp,
  readFile,
  rm,
  writeFile,
} from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import {
  afterEach,
  describe,
  it,
  vi,
} from 'vitest';

import { Runner as CliGenerateMustHavesAttributeFiles } from '../../../../cli/generate/must-haves/attribute-files.js';

import type {
  Tests_Cli_Generate_MustHaves_AttributeFiles_Run_RefusesAConflictingPatternWithoutWriting_ProjectDirectory,
  Tests_Cli_Generate_MustHaves_AttributeFiles_Run_WritesEachConfiguredFileWithTheHeader_Content,
  Tests_Cli_Generate_MustHaves_AttributeFiles_Run_WritesEachConfiguredFileWithTheHeader_ProjectDirectory,
} from '../../../../types/tests/cli/generate/must-haves/attribute-files.test.d.ts';

/**
 * Tests - CLI - Generate - Must Haves - Attribute Files - Run.
 *
 * @since 0.49.0
 */
describe('run', () => {
  afterEach(() => {
    vi.restoreAllMocks();

    process.exitCode = 0;

    return;
  });

  it('writes each configured file with the header', async () => {
    const projectDirectory: Tests_Cli_Generate_MustHaves_AttributeFiles_Run_WritesEachConfiguredFileWithTheHeader_ProjectDirectory = await mkdtemp(join(tmpdir(), 'nova-attribute-files-'));

    try {
      await writeFile(join(projectDirectory, 'package.json'), '{"name":"example-project","private":true,"workspaces":["packages/*"]}\n', 'utf-8');

      await writeFile(join(projectDirectory, 'nova.config.json'), JSON.stringify({
        attributeFiles: {
          './packages/docker/.gitattributes': {
            bundles: ['docker-scripts'],
            patterns: ['*.sh text eol=lf'],
          },
        },
      }), 'utf-8');

      await mkdir(join(projectDirectory, 'packages', 'docker'), { recursive: true });

      vi.spyOn(process, 'cwd').mockReturnValue(projectDirectory);

      vi.spyOn(process['stdout'], 'write').mockImplementation(() => true);

      vi.spyOn(process['stderr'], 'write').mockImplementation(() => true);

      await CliGenerateMustHavesAttributeFiles.run({ replaceFile: true });

      const content: Tests_Cli_Generate_MustHaves_AttributeFiles_Run_WritesEachConfiguredFileWithTheHeader_Content = await readFile(join(projectDirectory, 'packages', 'docker', '.gitattributes'), 'utf-8');

      strictEqual(content, [
        '# This file is generated by @cbnventures/nova.',
        '# Do not edit manually.',
        '#',
        '# Run `nova generate must-haves attribute-files` to regenerate.',
        '# See: https://nova.cbnventures.io/docs/cli/generators/must-haves/attribute-files',
        '',
        'rootfs/** text eol=lf',
        'project/** text eol=lf',
        'stages/** text eol=lf',
        '*.sh text eol=lf',
        '',
      ].join('\n'));
    } finally {
      await rm(projectDirectory, {
        recursive: true,
        force: true,
      });
    }

    return;
  });

  it('refuses a conflicting pattern without writing', async () => {
    const projectDirectory: Tests_Cli_Generate_MustHaves_AttributeFiles_Run_RefusesAConflictingPatternWithoutWriting_ProjectDirectory = await mkdtemp(join(tmpdir(), 'nova-attribute-files-'));

    try {
      await writeFile(join(projectDirectory, 'package.json'), '{"name":"example-project","private":true,"workspaces":["packages/*"]}\n', 'utf-8');

      await writeFile(join(projectDirectory, 'nova.config.json'), JSON.stringify({
        attributeFiles: {
          './packages/docker/.gitattributes': {
            bundles: ['docker-scripts'],
            patterns: ['rootfs/** binary'],
          },
        },
      }), 'utf-8');

      vi.spyOn(process, 'cwd').mockReturnValue(projectDirectory);

      vi.spyOn(process['stdout'], 'write').mockImplementation(() => true);

      vi.spyOn(process['stderr'], 'write').mockImplementation(() => true);

      strictEqual(await CliGenerateMustHavesAttributeFiles.run({}), 'cancelled');

      strictEqual(process.exitCode, 1);

      strictEqual(await readFile(join(projectDirectory, 'packages', 'docker', '.gitattributes'), 'utf-8').catch(() => 'missing'), 'missing');
    } finally {
      await rm(projectDirectory, {
        recursive: true,
        force: true,
      });
    }

    return;
  });

  return;
});
